import { ORACLE_WORLD_NAME } from "../pins.js";

/**
 * Minimal server.properties handling. Minecraft writes plain `key=value`
 * lines; we preserve unknown lines (comments included) verbatim, replace
 * managed keys in place, and append missing ones. Values this tool manages
 * never need .properties escaping.
 */
export function parseServerProperties(content: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#") || line.startsWith("!")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    map.set(line.slice(0, eq).trim(), line.slice(eq + 1).trim());
  }
  return map;
}

/** The keys the oracle run forces, per the API contract. */
export function oracleServerProperties(seed: string, opts?: { serverPort?: number }): Record<string, string> {
  const props: Record<string, string> = {
    "level-seed": seed,
    "level-name": ORACLE_WORLD_NAME,
    "online-mode": "false",
    "view-distance": "2",
    "spawn-protection": "0",
    "max-tick-time": "-1",
  };
  if (opts?.serverPort !== undefined) props["server-port"] = String(opts.serverPort);
  return props;
}

/**
 * Merge `overrides` into an existing server.properties body (pack/overlay
 * supplied), preserving everything else. `existing === null` produces a fresh
 * file.
 */
export function mergeServerProperties(
  existing: string | null,
  overrides: Record<string, string>,
): string {
  const pending = new Map(Object.entries(overrides));
  const out: string[] = [];

  if (existing !== null) {
    for (const rawLine of existing.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (line !== "" && !line.startsWith("#") && !line.startsWith("!")) {
        const eq = line.indexOf("=");
        if (eq > 0) {
          const key = line.slice(0, eq).trim();
          if (pending.has(key)) {
            out.push(`${key}=${pending.get(key)!}`);
            pending.delete(key);
            continue;
          }
        }
      }
      out.push(rawLine);
    }
    // Drop trailing blank line so appended keys stay tidy; re-added below.
    while (out.length > 0 && out[out.length - 1] === "") out.pop();
  } else {
    out.push("# Generated by seedmap (oracle headless server)");
  }

  for (const [key, value] of pending) out.push(`${key}=${value}`);
  return out.join("\n") + "\n";
}
